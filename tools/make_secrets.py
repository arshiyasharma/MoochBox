"""Turn .env into MoochBox/secrets.h for the Arduino sketch.

Run from the project root (again after every .env change):

    python3 tools/make_secrets.py

- Checks every required value is filled in and valid.
- The owner password is NOT copied: only a salted SHA-256 hash goes in.
    hash = SHA-256( salt bytes + password bytes ), both stored as hex
- secrets.h is gitignored and only readable by you.
- No secret values are printed.

Standard library only.
"""

import hashlib
import secrets
import subprocess
import sys
from pathlib import Path
from envfile import ENV_PATH, load_env

ROOT = ENV_PATH.parent
OUT_PATH = ROOT / "MoochBox" / "secrets.h"

# key in .env -> name in secrets.h (copied as plain text)
PLAIN_KEYS = {
    "SPOTIFY_CLIENT_ID": "SPOTIFY_CLIENT_ID",
    "SPOTIFY_CLIENT_SECRET": "SPOTIFY_CLIENT_SECRET",
    "SPOTIFY_REFRESH_TOKEN": "SPOTIFY_REFRESH_TOKEN",
    "MOOCHBOX_WIFI_PASSWORD": "MOOCHBOX_WIFI_PASSWORD",
    "MOOCHBOX_HOTSPOT_SSID": "HOTSPOT_SSID",
    "MOOCHBOX_HOTSPOT_PASSWORD": "HOTSPOT_PASSWORD",
}
OWNER_KEY = "MOOCHBOX_OWNER_PASSWORD"


def c_string(value: str) -> str:
    """Escape a value as a C string literal (UTF-8, non-ASCII as octal)."""
    out = []
    for byte in value.encode("utf-8"):
        ch = chr(byte)
        if ch in '\\"':
            out.append("\\" + ch)
        elif 32 <= byte < 127 and ch != "?":  # '?' avoids C trigraphs
            out.append(ch)
        else:
            out.append(f"\\{byte:03o}")
    return '"' + "".join(out) + '"'


def check(env: dict) -> list:
    """Return a list of problems (empty = all good)."""
    problems = []
    for key in list(PLAIN_KEYS) + [OWNER_KEY]:
        if not env.get(key):
            hint = " (run: python3 tools/get_token.py)" if key == "SPOTIFY_REFRESH_TOKEN" else ""
            problems.append(f"{key} is empty{hint}")

    owner = env.get(OWNER_KEY, "")
    if owner and len(owner) < 10:
        problems.append(f"{OWNER_KEY} must be at least 10 characters")

    for key in ("MOOCHBOX_WIFI_PASSWORD", "MOOCHBOX_HOTSPOT_PASSWORD"):
        value = env.get(key, "")
        if value and not 8 <= len(value.encode("utf-8")) <= 63:
            problems.append(f"{key} must be 8-63 characters (WiFi/WPA2 rule)")

    ssid = env.get("MOOCHBOX_HOTSPOT_SSID", "")
    if len(ssid.encode("utf-8")) > 32:
        problems.append("MOOCHBOX_HOTSPOT_SSID is longer than 32 bytes (WiFi limit)")
    return problems


def build_header(env: dict) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.sha256(salt + env[OWNER_KEY].encode("utf-8")).hexdigest()

    lines = [
        "// AUTO-GENERATED by tools/make_secrets.py from .env. Do not edit.",
        "// Gitignored: never commit this file.",
        "#pragma once",
        "",
    ]
    for env_key, c_name in PLAIN_KEYS.items():
        lines.append(f"static const char {c_name}[] = {c_string(env[env_key])};")
    lines += [
        "",
        "// Owner password: salted SHA-256 only. hash = SHA-256(salt bytes + password bytes)",
        f'static const char OWNER_PASSWORD_SALT_HEX[] = "{salt.hex()}";',
        f'static const char OWNER_PASSWORD_HASH_HEX[] = "{digest}";',
        "",
    ]
    return "\n".join(lines)


def is_gitignored(path: Path) -> bool:
    try:
        result = subprocess.run(
            ["git", "check-ignore", "-q", str(path)],
            cwd=ROOT, capture_output=True,
        )
        return result.returncode == 0
    except FileNotFoundError:
        return True  # no git installed: nothing to commit it with


def main(env_path: Path = ENV_PATH, out_path: Path = OUT_PATH) -> None:
    if not env_path.exists():
        print(f"✗ No .env found at {env_path}. Copy .env.example to .env first.")
        sys.exit(1)

    env = load_env(env_path)
    problems = check(env)
    if problems:
        print("✗ Fix these in .env, then run again:")
        for problem in problems:
            print(f"  - {problem}")
        sys.exit(1)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(build_header(env), encoding="utf-8")
    out_path.chmod(0o600)

    print(f"✓ Wrote {out_path.relative_to(ROOT) if out_path.is_relative_to(ROOT) else out_path}")
    print("  Owner password stored as a salted hash only.")
    print(f"  Hotspot MoochBox will join: {env['MOOCHBOX_HOTSPOT_SSID']}")
    if "'" in env["MOOCHBOX_HOTSPOT_SSID"]:
        print("  ! Your hotspot name has a straight apostrophe ('). iPhones often use a "
              "curly one (’). If MoochBox can't find the hotspot, copy the exact name "
              "from Settings → General → About → Name.")
    if out_path == OUT_PATH and not is_gitignored(out_path):
        print("  ! WARNING: secrets.h is NOT gitignored. Don't commit it.")
    print("Next: open MoochBox/MoochBox.ino in Arduino IDE and upload.")


if __name__ == "__main__":
    main()
